"""AI-assisted Codex browser regression checks for the isolated experience.
Requires the already installed Playwright package and Chrome, not a runtime dependency.
Run with the repo root served at http://127.0.0.1:8766.
"""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / '.qa'
OUT.mkdir(exist_ok=True)
BASE = 'http://127.0.0.1:8766/site/'
checks, errors = [], []

def check(name, test):
    try:
        test()
        checks.append({'name': name, 'passed': True})
        print('PASS', name, flush=True)
    except Exception as e:
        checks.append({'name': name, 'passed': False, 'error': str(e)[:500]})
        print('FAIL', name, str(e)[:180], flush=True)

def require(value, why):
    assert value, why

with sync_playwright() as p:
    b = p.chromium.launch(channel='chrome', headless=True, args=['--enable-unsafe-swiftshader'])
    page = b.new_page(viewport={'width':1440,'height':1000}, device_scale_factor=1)
    page.set_default_timeout(8000)
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.route('https://fonts.googleapis.com/**', lambda r:r.abort())
    page.goto(BASE, wait_until='domcontentloaded')
    page.wait_for_function("document.querySelector('#missionRows').textContent === '1,276'")
    page.screenshot(path=str(OUT/'home-desktop.png'), full_page=True)
    check('NASA rows loaded, dark default', lambda: require(page.locator('html').get_attribute('data-theme')=='dark','not dark'))
    page.locator('[data-hero-g=earth]').click()
    check('Landing gravity comparison', lambda: require('hot gas rises' in page.locator('#heroFlameTitle').inner_text().lower(),'caption did not change'))
    page.locator('#startJourney').click()
    page.wait_for_timeout(400)
    check('Journey starts at ISS', lambda: require(page.locator('#hP').inner_text().startswith('14.7'),'wrong point'))
    page.locator('#journeyNext').click()
    page.wait_for_timeout(200)
    check('Moon Base fuel coverage distinguishes materials', lambda: require('68 tests' in page.locator('#homeCover').inner_text() and 'Not placeable' in page.locator('#homeCover').inner_text(),'coverage wrong'))
    page.screenshot(path=str(OUT/'analysis-desktop.png'))
    page.locator('#journeyNext').click()
    check('Spacesuit reaches full oxygen range', lambda: require(page.locator('#hO2').inner_text().startswith('100'),'wrong point'))
    page.locator('#journeyNext').click()
    page.locator('#journeyNext').click()
    check('Journey ends in evidence brief', lambda: require(page.locator('#brief').is_visible(),'brief missing'))
    page.wait_for_timeout(350)
    page.screenshot(path=str(OUT/'brief.png'))
    page.locator('#briefClose').focus()
    page.keyboard.press('Tab')
    check('Evidence dialog contains keyboard focus', lambda: require(page.locator('#brief').evaluate('e=>e.contains(document.activeElement)'),'focus escaped dialog'))
    page.emulate_media(media='print')
    page.evaluate("document.body.classList.add('printing')")
    page.pdf(path=str(OUT/'evidence-brief.pdf'),format='A4',print_background=True)
    from pypdf import PdfReader
    check('Evidence brief exports as one A4 page', lambda: require(len(PdfReader(OUT/'evidence-brief.pdf').pages)==1,'brief overflow'))
    page.evaluate("document.body.classList.remove('printing')")
    page.emulate_media(media='screen')
    page.keyboard.press('Escape')
    page.locator('[data-fuel=solid]').click()
    check('Material gap stays explicit', lambda: require(page.locator('#mapEmpty').is_visible() and page.locator('#homeSvg .tdot').count()==0,'material filter misleading'))
    page.locator('[data-fuel=""]').click()
    page.locator('#probeO').fill('34')
    page.locator('#probeO').press('Tab')
    page.locator('#probeP').fill('8')
    page.locator('#probeP').press('Tab')
    check('Exact numeric probe inputs work', lambda: require(page.locator('#hO2').inner_text().startswith('34') and page.locator('#hP').inner_text().startswith('8.0'),'probe did not update'))
    page.locator('#homeSvg').focus()
    page.keyboard.press('ArrowRight')
    check('Map keyboard control', lambda: require(not page.locator('#hP').inner_text().startswith('8.0'),'arrow did not move probe'))
    page.locator('#bar [data-ask]').click()
    page.locator('#ask').fill('What do we know about fabric at 30% oxygen and 10.2 psi?')
    page.locator('#compose button').click()
    page.wait_for_selector('#msgs .bot:nth-last-child(1)')
    page.wait_for_timeout(600)
    check('Assistant answers from local evidence', lambda: require('solid' in page.locator('#msgs').inner_text().lower() and page.locator('.typing').count()==0,'no local answer'))
    check('Assistant includes clickable NASA sources', lambda: require(page.locator('.answer-sources a').count()>0,'source links missing'))
    page.locator('#chatClose').click()
    page.locator('[data-m=advanced]').click()
    check('Catalogue retains 24 investigations', lambda: require(page.locator('#catTable tbody tr').count()==24,'catalogue changed'))
    page.locator('#catSearch').fill('SAME')
    check('Catalogue search includes SAME research as well as experiments', lambda: require(page.locator('#catTable tbody tr').count()==3,'search failed'))
    page.locator('#catSearch').fill('')
    page.locator('[data-v=data]').click()
    page.locator('#fSearch').fill('FLEX')
    page.wait_for_timeout(150)
    check('Research filters', lambda: require(page.locator('#fCount').inner_text()=='274','FLEX count wrong'))
    with page.expect_download() as dl:
        page.locator('#tCsv').click()
    download=dl.value
    download.save_as(OUT/'filtered-tests.csv')
    check('CSV export preserves provenance and filtered row count', lambda: require(len((OUT/'filtered-tests.csv').read_text().splitlines())==275 and 'source_line' in (OUT/'filtered-tests.csv').read_text().splitlines()[0],'CSV wrong'))
    page.locator('#fSearch').fill('zzzz-no-match')
    page.wait_for_function("document.querySelector('#fCount').textContent === '0'")
    check('Empty filters are clearly explained', lambda: require(page.locator('#fCount').inner_text()=='0','empty result wrong'))
    page.locator('#fReset').click()
    page.screenshot(path=str(OUT/'research-desktop.png'))
    page.locator('.bar [data-page=sim]').click()
    frame=page.frame_locator('#simFrame')
    frame.locator('#inv option').first.wait_for(state='attached',timeout=30000)
    page.wait_for_timeout(1500)
    check('Flame lab starts', lambda: require(frame.locator('#sourceSummary').inner_text().find('FLEX')>=0,'lab has no NASA test'))
    check('WebGL renderer runs', lambda: require(not frame.locator('body').get_attribute('class') or 'nogpu' not in frame.locator('body').get_attribute('class'),'WebGL fallback used'))
    page.screenshot(path=str(OUT/'lab-desktop.png'))
    frame.locator('#atmosphereSettings').evaluate('(e)=>e.open=true')
    frame.locator('[data-lab-preset=suit]').click()
    check('Lab spacesuit preset is 100 percent at 4.3 psi', lambda: require(frame.locator('#o2').input_value()=='100' and frame.locator('#psi').input_value()=='4.3','sliders clipped the point'))
    frame.locator('label:has(input[name=g][value="1"])').click()
    check('Gravity changes hypothetical conditions label', lambda: require('MODIFIED' in frame.locator('#labMode').inner_text(),'label wrong'))
    frame.locator('[data-lab-preset=record]').click()
    frame.locator('#pause').click()
    check('Pause control works', lambda: require(frame.locator('#pause').inner_text()=='Play','pause failed'))
    frame.locator('#pause').click()
    page.locator('.bar [data-page=analysis]').click()
    lab=page.frames[-1]
    check('Hidden lab suspends GPU updates', lambda: require(lab.evaluate('pageActive') is False,'hidden simulation still active'))
    before=lab.evaluate('clock')
    page.wait_for_timeout(200)
    check('Hidden simulation clock stays stopped',lambda:require(lab.evaluate('clock')==before,'simulation advanced offscreen'))
    # The map-to-lab handoff must keep the full spacesuit range too.
    page.locator('[data-m=simple]').click()
    page.locator('#journeyTrack [data-step="2"]').click()
    page.locator('#homeBurn').click()
    page.wait_for_timeout(250)
    check('Map to lab atmosphere transfer', lambda: require(frame.locator('#o2').input_value()=='100' and frame.locator('#psi').input_value()=='4.3','handoff lost values'))
    # Standalone CSS fallback.
    fallback=b.new_page(viewport={'width':1280,'height':900})
    fallback.on('pageerror',lambda e:errors.append(str(e)))
    fallback.route('https://fonts.googleapis.com/**',lambda r:r.abort())
    fallback.goto(BASE+'sim.html?css',wait_until='domcontentloaded')
    fallback.wait_for_selector('#cssFlame .ff-flame')
    check('CSS fallback is available with one-shot outcome animation', lambda: require('single-play' in fallback.locator('.ff-flame').get_attribute('class'),'fallback still loops'))
    fallback.close()
    for width in [375,768,1440]:
        for suffix,label in [('', 'home'),('#analysis','analysis'),('#resources','research'),('learn.html','learn')]:
            page.set_viewport_size({'width':width,'height':900})
            page.goto(BASE+suffix,wait_until='domcontentloaded')
            page.wait_for_timeout(250)
            check(f'{label} fits {width}px',lambda:require(page.evaluate('document.documentElement.scrollWidth <= innerWidth'),'horizontal overflow'))
            if width==375: page.screenshot(path=str(OUT/(label+'-mobile.png')),full_page=label=='home')
    page.set_viewport_size({'width':1440,'height':1000})
    page.goto(BASE+'learn.html',wait_until='domcontentloaded')
    check('Six captioned learning videos remain available',lambda:require(page.locator('video track').count()==6,'video tracks missing'))
    check('Learn shows one lesson at a time',lambda:require(page.locator('.lesson:visible').count()==1,'lessons still stacked'))
    page.locator('#lessonSelect').select_option('1')
    check('Chapter navigation opens gravity lesson',lambda:require(page.locator('#l2').is_visible() and page.url.endswith('#l2'),'chapter navigation failed'))
    page.locator('#l2 [data-gravity="1"]').click()
    check('Gravity lesson interactive calculation works',lambda:require(page.locator('#flowForce').inner_text()=='100%','gravity illustration did not update'))
    page.locator('#lessonNext').click()
    check('Lesson next button and deep link agree',lambda:require(page.locator('#l3').is_visible() and page.url.endswith('#l3'),'next lesson failed'))
    page.go_back(wait_until='domcontentloaded')
    check('Browser back restores selected lesson',lambda:require(page.locator('#l2').is_visible(),'history failed'))
    page.locator('#lessonSelect').select_option('11')
    check('Formula sheet is directly accessible',lambda:require(page.locator('#sheet').is_visible(),'reference unavailable'))
    page.locator('#theme').click()
    check('Theme switch in Learn',lambda:require(page.locator('html').get_attribute('data-theme') is None,'light theme failed'))
    page.goto(BASE,wait_until='domcontentloaded')
    check('Theme persists across pages',lambda:require(page.locator('html').get_attribute('data-theme') is None,'theme not persistent'))
    page.screenshot(path=str(OUT/'home-light.png'),full_page=True)
    page.emulate_media(reduced_motion='reduce')
    page.wait_for_function("document.querySelector('#heroFlow').dataset.paused==='true'")
    check('Reduced motion removes decorative animation',lambda:require(page.locator('#heroFlow').get_attribute('data-paused')=='true','animation still active'))
    check('No browser script errors',lambda:require(not errors, '\n'.join(errors)))
    b.close()

(OUT/'results.json').write_text(json.dumps({'checks':checks,'errors':errors},indent=2),encoding='utf-8')
print(json.dumps({'passed':sum(c['passed'] for c in checks),'total':len(checks),'errors':errors}),flush=True)
raise SystemExit(1 if errors or any(not c['passed'] for c in checks) else 0)
