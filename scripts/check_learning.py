"""AI-assisted Codex UI, scientific-data and media regression checks for the learning rework."""
import json
from pathlib import Path
from playwright.sync_api import sync_playwright

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'.qa'/'learning'
OUT.mkdir(parents=True,exist_ok=True)
BASE='http://127.0.0.1:8766/site/'
checks=[]
errors=[]

def verify(name,condition):
    assert condition,name
    checks.append(name)
    print('PASS',name,flush=True)

with sync_playwright() as p:
 b=p.chromium.launch(channel='chrome',headless=True,args=['--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'])
 page=b.new_page(viewport={'width':1440,'height':1050})
 page.set_default_timeout(8000)
 page.route('https://fonts.googleapis.com/**',lambda r:r.abort())
 page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto(BASE+'learn.html',wait_until='domcontentloaded')
 page.wait_for_function("document.querySelector('#outcomeCounts').textContent.startsWith('274 rows')")
 verify('Six interactive experiments initialize',page.locator('.learning-lab').count()==6)
 verify('No unsolicited media playback',page.evaluate('Array.from(document.querySelectorAll("video")).every(v=>v.paused)'))
 def lesson(n):
    page.locator('#lessonSelect').select_option(str(n-1))
    page.locator(f'#l{n}-tab-0').click()
    page.wait_for_timeout(100)
 for supply in ['fuel','oxygen','heat']:
    page.locator(f'[data-supply={supply}]').click()
    verify(f'Interrupt {supply} stops conceptual flame',page.locator('#lab-l1 .concept-flame').evaluate("e=>e.classList.contains('off')"))
    verify(f'{supply} explanation names the changed supply',supply in page.locator('#lab-l1 .lab-result').inner_text().lower())
    page.locator('#lab-l1 .activity-reset').click()
    verify(f'Reset after {supply} restores all supplies',page.locator('#lab-l1 .concept-flame').evaluate("e=>!e.classList.contains('off')"))
 page.locator('#lab-l1 .lab-prediction button').last.click()
 verify('Prediction receives explanatory feedback','needs enough heat' in page.locator('#lab-l1 .lab-feedback').inner_text())
 lesson(2)
 for g in ['0','0.166','0.378','1']:
    page.locator(f'#l2 [data-gravity="{g}"]').click()
    verify('Gravity value '+g,page.locator('#lab-l2 .lab-visual').get_attribute('data-g')==g)
    force=float(page.locator('#flowForce').inner_text().rstrip('%'))
    verify('Buoyant force comparison '+g,abs(force-float(g)*100)<.6)
 page.locator('#l2 [data-gravity="0"]').click()
 page.locator('#labFan').check()
 verify('Fan drives flow at zero g','even at 0 g' in page.locator('#flowResult').inner_text())
 page.locator('#flowPause').click()
 verify('Flow animation can pause',page.locator('#lab-l2 .lab-visual').get_attribute('data-paused')=='true')
 page.locator('#flowPause').click()
 page.screenshot(path=str(OUT/'gravity-desktop.png'))
 lesson(3)
 for preset,expected in [('21,14.7',3.087),('30,10.2',3.06),('100,4.3',4.3)]:
    page.locator(f'[data-mix="{preset}"]').click()
    verify('Dry partial pressure '+preset,abs(float(page.locator('#mixPartial').inner_text())-expected)<.006)
 page.locator('#mixLock').check()
 for pressure in [4,7.4,10.2,14.7,16]:
    page.locator('#mixP').evaluate('(e,v)=>{e.value=v;e.dispatchEvent(new Event("input"));}',pressure)
    verify('Reference lock at pressure '+str(pressure),page.locator('#mixPartial').inner_text()=='3.07')
 verify('Locked oxygen is explicitly disabled',page.locator('#mixO').is_disabled())
 page.locator('#lab-l3 .activity-reset').click()
 verify('Partial pressure reset unlocks controls',not page.locator('#mixO').is_disabled() and page.locator('#mixO').input_value()=='21')
 page.screenshot(path=str(OUT/'pressure-desktop.png'))
 lesson(4)
 for oxygen,ratio,nitrogen in [(21,3.76,23),(30,2.33,14),(50,1,6),(100,0,0)]:
    page.locator(f'[data-dilution="{oxygen}"]').click()
    verify('Six oxygen pairs fixed at '+str(oxygen),page.locator('#dilutionMolecules .oxygen').count()==6)
    verify('Nitrogen ratio at '+str(oxygen),float(page.locator('#dilutionRatio').inner_text())==ratio)
    verify('Rounded nitrogen picture at '+str(oxygen),int(page.locator('#dilutionN').inner_text())==nitrogen)
 lesson(5)
 page.locator('#diffHalf').click()
 verify('Half pressure gives nearly twice diffusion',abs(float(page.locator('#diffCoefficient').inner_text().rstrip('×'))-2)<.02)
 verify('Spread distance uses square root',abs(float(page.locator('#diffDistance').inner_text().rstrip('×'))-2**.5)<.02)
 page.locator('#diffRun').click()
 page.wait_for_timeout(600)
 verify('Diffusion comparison advances',float(page.locator('#diffTime').input_value())>0)
 page.locator('#diffRun').click()
 t=page.locator('#diffTime').input_value()
 page.wait_for_timeout(150)
 verify('Diffusion pause stops elapsed time',page.locator('#diffTime').input_value()==t)
 page.locator('#diffTime').evaluate('(e)=>{e.value=.5;e.dispatchEvent(new Event("input"));}')
 verify('Motion-free scrub shows selected time',page.locator('#diffTOut').inner_text()=='0.50')
 page.locator('#lab-l5 .activity-reset').click()
 verify('Diffusion reset clears elapsed time',page.locator('#diffTime').input_value()=='0')
 lesson(6)
 rows=json.loads((ROOT/'data/tests.web.json').read_text())
 flex=sorted([r for r in rows if r['accession']=='PSI-69'],key=lambda r:(float('inf') if r['o2_pct'] is None else r['o2_pct'],r['source_line']))
 verify('FLEX row total is actual data',len(flex)==274 and page.locator('#outcomeCounts').inner_text().startswith('274 rows'))
 first=flex[0]
 verify('Selected record matches source test id',first['test_id'] in page.locator('#outcomeRecord').inner_text())
 page.locator('#revealOutcome').click()
 outcome='Went out by itself' if first['outcome']=='self_extinguished' else 'Kept burning' if first['outcome']=='burned' else 'Not recorded'
 shown=page.locator('#recordOutcome').inner_text()
 expected=outcome if first.get('burn_time_s') is None else outcome+', burn time '+('about ' if first.get('burn_time_approx') else '')+('%g' % first['burn_time_s'])+' s'
 verify('Revealed outcome and burn time match NASA row',shown==expected)
 gases=', '.join('%d%% %s' % (round(first[k]),n) for k,n in (('n2_pct','nitrogen'),('co2_pct','carbon dioxide'),('he_pct','helium')) if (first.get(k) or 0)>0)
 verify('Record shows the rest of the gas mixture from the NASA row',gases in page.locator('#outcomeRecord').inner_text())
 verify('Source filename and line retained',first['source'] in page.locator('#outcomeRecord').inner_text() and str(first['source_line']) in page.locator('#outcomeRecord').inner_text())
 for pressure in ['low','cabin','high']:
    page.locator('#outcomePressure').select_option(pressure)
    expected=[r for r in flex if r['pressure_psi'] is not None and (r['pressure_psi']<12 if pressure=='low' else 12<=r['pressure_psi']<=16 if pressure=='cabin' else r['pressure_psi']>16)]
    verify('FLEX pressure filter '+pressure,page.locator('#outcomeCounts').inner_text().startswith(str(len(expected))+' rows'))
 page.locator('#lab-l6 .activity-reset').click()
 page.locator('#outcomeNext').click()
 verify('Record paging retains full set','25 to 48 of 274' in page.locator('#outcomePage').inner_text())
 page.locator('#outcomePrev').click()
 page.locator('#lab-l6 .lab-visual > button').click()
 verify('Comparison uses real same-oxygen records','193R002' in page.locator('.paired-records').inner_text() and '175R001' in page.locator('.paired-records').inner_text())
 page.screenshot(path=str(OUT/'outcomes-desktop.png'))
 verify('Progress records exploration','6 of 6' in page.locator('#labProgress').inner_text())
 # Play all six lesson videos.
 for n in range(1,7):
    lesson(n)
    page.locator(f'#l{n}-tab-1').click()
    v=page.locator(f'#l{n} video')
    v.evaluate('v=>v.play()')
    page.wait_for_function(f"document.querySelector('#l{n} video').currentTime>.15")
    verify('Video '+str(n)+' decodes and plays',v.evaluate('v=>!v.paused && v.readyState>=2 && v.videoWidth===1920'))
    v.evaluate('v=>{v.currentTime=12;v.playbackRate=1.25;v.volume=.4;}')
    page.wait_for_function(f"!document.querySelector('#l{n} video').seeking && document.querySelector('#l{n} video').currentTime>11.5")
    verify('Video seeking, volume and speed '+str(n),v.evaluate('v=>v.currentTime>11.5 && v.volume===.4 && v.playbackRate===1.25'))
    page.locator(f'#l{n}-tab-0').click()
    verify('Leaving Watch pauses video '+str(n),v.evaluate('v=>v.paused'))
    page.wait_for_timeout(50)
    verify('Leaving Watch releases video source '+str(n),v.locator('source').get_attribute('src') is None)
    page.locator(f'#l{n}-tab-1').click()
    page.wait_for_function(f"document.querySelector('#l{n} video').readyState>=1")
    page.wait_for_function(f"document.querySelector('#l{n} video').currentTime>11.5")
    verify('Returning to Watch restores playhead '+str(n),v.evaluate('v=>v.currentTime>11.5 && v.paused'))
    page.locator(f'#l{n}-tab-0').click()
 # Keyboard tabs, deep links and progress persistence.
 lesson(1)
 page.locator('#l1-tab-0').focus();page.keyboard.press('ArrowRight')
 verify('Lesson view tabs support keyboard navigation',page.locator('#l1-tab-1').get_attribute('aria-selected')=='true')
 page.locator('#l1-tab-1').press('End')
 verify('End key opens Explanation',page.locator('#l1-tab-2').get_attribute('aria-selected')=='true')
 page.reload(wait_until='domcontentloaded')
 verify('Exploration progress survives reload','6 of 6' in page.locator('#labProgress').inner_text())
 page.locator('.lab-progress button').click()
 verify('Progress can be cleared','0 of 6' in page.locator('#labProgress').inner_text())
 for width in [375,768,1440]:
    page.set_viewport_size({'width':width,'height':1000})
    for theme in ['light','dark']:
       page.evaluate('(t)=>{if(t==="dark")document.documentElement.dataset.theme=t;else delete document.documentElement.dataset.theme;}',theme)
       for n in range(1,7):
          lesson(n)
          verify(f'Lesson {n}, {theme}, {width}px fits',page.evaluate('document.documentElement.scrollWidth<=innerWidth'))
          page.locator(f'#l{n}').screenshot(path=str(OUT/f'l{n}-{theme}-{width}.png'))
 page.goto(BASE,wait_until='domcontentloaded')
 page.wait_for_function("document.querySelector('#missionRows').textContent==='1,276'")
 verify('Homepage keeps Analysis name',page.locator('.home-nav a').first.inner_text()=='Analysis')
 verify('Homepage uses concrete data-coverage explanation','263 solid-material test rows' in page.locator('#materialGap').inner_text())
 for theme in ['light','dark']:
    page.evaluate('(t)=>{if(t==="dark")document.documentElement.dataset.theme=t;else delete document.documentElement.dataset.theme;}',theme)
    page.wait_for_timeout(120)
    color=page.locator('.hero-chamber').evaluate('e=>getComputedStyle(e).backgroundColor')
    verify('Gravity study theme '+theme,color==('rgb(255, 255, 255)' if theme=='light' else 'rgb(16, 26, 38)'))
    page.locator('.hero-chamber').screenshot(path=str(OUT/f'hero-{theme}.png'))
 page.locator('#heroFan').check()
 verify('Homepage ventilation changes study','fan moves gas' in page.locator('#heroFlameTitle').inner_text())
 page.locator('#heroMotion').click()
 verify('Homepage motion pauses',page.locator('#heroFlow').get_attribute('data-paused')=='true')
 page.emulate_media(reduced_motion='reduce')
 page.goto(BASE+'learn.html#l2',wait_until='domcontentloaded')
 verify('Reduced motion starts flow study paused',page.locator('#lab-l2 .lab-visual').get_attribute('data-paused')=='true')
 verify('Reduced motion still permits deliberate animation',page.locator('#flowPause').inner_text()=='Animate motion')
 page.locator('#flowPause').click()
 verify('Explicit motion opt-in works',page.locator('#lab-l2 .lab-visual').get_attribute('data-paused')=='false')
 verify('No browser script exceptions',not errors)
 (OUT/'results.json').write_text(json.dumps({'passed':len(checks),'checks':checks,'errors':errors},indent=2),encoding='utf-8')
 b.close()
 print(f'ALL {len(checks)} LEARNING CHECKS PASSED',flush=True)
